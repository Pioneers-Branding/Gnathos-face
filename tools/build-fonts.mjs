// Self-hosts the site's web fonts so visitors' browsers never contact Google Fonts
// (faster first paint, and no visitor IP addresses shared with a third party).
//
//   node tools/build-fonts.mjs
//
// 1. Inter + Cormorant Garamond (latin + latin-ext subsets)
// 2. Material Symbols Outlined, subset to ONLY the icon names actually used in the PHP
//    templates (≈30 KB instead of ≈1.1 MB). Re-run after adding a new icon to any page.
//
// Writes woff2 files to asset/fonts/ and the @font-face rules to src/fonts.css
// (imported by src/site.css, compiled by `npm run css`).

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const OUT_DIR = join(ROOT, 'asset', 'fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);
const SKIP_DIRS = new Set(['node_modules', '.git', 'seo-plan', 'asset', 'src', 'tools', '.vscode']);

mkdirSync(OUT_DIR, { recursive: true });

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, acc);
    else if (name.endsWith('.php')) acc.push(p);
  }
  return acc;
}

function usedIcons() {
  const names = new Set();
  const rx = /material-symbols-outlined[^>]*>\s*([a-z0-9_]+)\s*</g;
  for (const f of walk(ROOT)) {
    const s = readFileSync(f, 'utf8');
    let m;
    while ((m = rx.exec(s))) names.add(m[1]);
  }
  // Icons referenced from PHP arrays / helpers (gna_icon('name'))
  const rx2 = /gna_icon\(\s*'([a-z0-9_]+)'/g;
  for (const f of walk(ROOT)) {
    const s = readFileSync(f, 'utf8');
    let m;
    while ((m = rx2.exec(s))) names.add(m[1]);
  }
  return [...names].sort();
}

async function getCss(url) {
  const r = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(`${r.status} for ${url}`);
  return r.text();
}

async function download(url, file) {
  const r = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(`${r.status} for ${url}`);
  writeFileSync(join(OUT_DIR, file), Buffer.from(await r.arrayBuffer()));
}

// Parses Google's css2 response into blocks: { subset, style, weight, url, unicodeRange }
function parseBlocks(css) {
  const blocks = [];
  const rx = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}|@font-face\s*\{([^}]+)\}/g;
  let m;
  while ((m = rx.exec(css))) {
    const subset = m[1] || 'all';
    const body = m[2] || m[3];
    const get = (k) => (body.match(new RegExp(`${k}:\\s*([^;]+);`)) || [])[1];
    blocks.push({
      subset,
      family: get('font-family').replace(/['"]/g, ''),
      style: get('font-style'),
      weight: get('font-weight'),
      url: (body.match(/url\(([^)]+)\)/) || [])[1],
      unicodeRange: get('unicode-range'),
    });
  }
  return blocks;
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

async function main() {
  let fontCss = '/* Generated by tools/build-fonts.mjs — do not edit by hand. */\n';
  const seen = new Map();

  const textFamilies = [
    'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&display=swap',
    'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;0,700;1,400;1,500&display=swap',
  ];
  for (const u of textFamilies) {
    for (const b of parseBlocks(await getCss(u))) {
      if (!KEEP_SUBSETS.has(b.subset)) continue;
      let file = seen.get(b.url);
      if (!file) {
        file = `${slug(b.family)}-${b.style}-${b.subset}${seen.size ? '' : ''}.woff2`;
        // Variable fonts reuse one file across weights; static ones need the weight in the name.
        if ([...seen.values()].includes(file)) file = file.replace('.woff2', `-${b.weight}.woff2`);
        seen.set(b.url, file);
        await download(b.url, file);
      }
      fontCss += `@font-face{font-family:'${b.family}';font-style:${b.style};font-weight:${b.weight};font-display:swap;src:url(/asset/fonts/${file}) format('woff2');unicode-range:${b.unicodeRange};}\n`;
    }
  }

  const icons = usedIcons();
  const iconUrl = `https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,400,0..1,0&icon_names=${icons.join(',')}&display=block`;
  const [ib] = parseBlocks(await getCss(iconUrl));
  await download(ib.url, 'material-symbols-outlined.woff2');
  fontCss += `@font-face{font-family:'Material Symbols Outlined';font-style:normal;font-weight:400;font-display:block;src:url(/asset/fonts/material-symbols-outlined.woff2) format('woff2');}\n`;

  writeFileSync(join(ROOT, 'src', 'fonts.css'), fontCss);
  console.log(`fonts: ${seen.size} text font files, ${icons.length} icons → ${relative(ROOT, OUT_DIR)}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
