<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Are all oral cysts and tumors cancerous?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">keyboard_arrow_down</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    No. The majority of oral cysts are benign and respond well to surgical removal. While some oral lesions can be precancerous or malignant, early detection and treatment offer excellent outcomes. A biopsy provides definitive diagnosis to guide appropriate treatment.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Will I need general anesthesia for cyst removal?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">keyboard_arrow_down</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Treatment is typically performed under local anesthesia with sedation or under general anesthesia, depending on the lesion size, location, and complexity. Your surgeon will discuss the most appropriate anesthesia option during your pre-operative consultation. Small lesions can often be removed under local anesthesia alone.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    How long does it take for the biopsy results?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">keyboard_arrow_down</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Histopathology results are typically available within 5-7 working days. For urgent cases or during surgery, frozen section analysis can provide preliminary results within 20-30 minutes. Your treating team will contact you with results and discuss the next steps in your treatment plan.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Can oral cysts recur after removal?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">keyboard_arrow_down</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Some cyst types have a higher recurrence rate than others. Complete enucleation with careful removal of the cyst lining significantly reduces recurrence risk. Certain aggressive lesions like ameloblastomas may require more extensive surgery or long-term monitoring. Your surgeon will explain the specific recurrence risk for your diagnosis.
                </div>
</details>
<details class="group bg-surface-container-lowest border border-surface-variant rounded-lg [&_summary::-webkit-details-marker]:hidden">
<summary class="flex items-center justify-between p-6 cursor-pointer font-semibold text-primary">
                    Will I need bone grafting after cyst removal?
                    <span class="material-symbols-outlined transition duration-300 group-open:-rotate-180">keyboard_arrow_down</span>
</summary>
<div class="px-6 pb-6 text-on-surface-variant text-sm">
                    Not always. Small cysts that don't significantly compromise bone structure often heal naturally. Larger cysts causing substantial bone loss may require bone grafting or reconstruction to restore jaw integrity. Your surgeon will assess the defect size during surgery and recommend appropriate reconstruction if needed.
                </div>
</details>
