<p class="gna-lede">Yes — ear infections can cause jaw pain, and the reverse is also true. The two structures are anatomically intertwined, so pain from one is often felt in the other. Knowing which is the real source of the problem is the key to getting the right treatment.</p>
<h2 id="anatomy">Why the Ear and Jaw Overlap</h2>
<p>The temporomandibular joint (TMJ) sits just in front of the ear canal, separated from it by a paper-thin wall of bone. They share the same nerve supply (the auriculotemporal nerve and branches of the trigeminal nerve), and they use many of the same muscles. So when one is inflamed, the other is almost always affected.</p>
<p>Because the brain often can't tell exactly where the pain signal is coming from, ear pain can be felt as jaw pain, and jaw pain can be felt as ear pain. This overlap is the reason <a href="/blogs/causes-of-jaw-pain-on-one-side/">one-sided jaw pain</a> is so often misdiagnosed.</p>
<h2 id="ear">How Ear Infections Cause Jaw Pain</h2>
<p>An ear infection — whether it's otitis externa (outer ear), otitis media (middle ear), or mastoiditis — produces inflammation and pressure. That inflammation can spread to the TMJ through the shared nerve pathways, and the pressure changes in the middle ear are felt as discomfort in the jaw on the same side.</p>
<p>Ear infections that can radiate to the jaw include:</p>
<ul>
<li><strong>Acute otitis media</strong> — middle-ear infection, common in children but also in adults</li>
<li><strong>Otitis externa</strong> — "swimmer's ear," infection of the ear canal</li>
<li><strong>Mastoiditis</strong> — infection of the bone behind the ear</li>
<li><strong>Eustachian-tube dysfunction</strong> — pressure imbalance in the middle ear</li>
</ul>
<p>Each produces inflammation that, by proximity and shared nerves, refers pain to the jaw.</p>
