<h2 id="dental">Dental Causes</h2>
<ul>
<li>Crooked, crowded, or missing teeth (especially molars)</li>
<li>Dental midline shift</li>
<li>Premature loss of baby or adult teeth</li>
<li>Crossbite on one side</li>
<li>Habitual chewing on one side</li>
<li>Failed dental restorations altering the bite</li>
</ul>
<p>These respond well to orthodontics or restorative dentistry when the bones themselves are normal.</p>
<h2 id="softtissue">Soft-Tissue &amp; Nerve Causes</h2>
<ul>
<li><strong>Bell's palsy / facial nerve palsy</strong> — weakness on one side of the face</li>
<li><strong>Hemifacial spasm</strong> — involuntary muscle contractions on one side</li>
<li><strong>Muscle hypertrophy</strong> — overuse of one side (e.g., from chewing on one side only)</li>
<li><strong>Fat distribution differences</strong> — normal variation</li>
<li><strong>Romberg syndrome / Parry-Romberg</strong> — progressive loss of facial fat and tissue on one side</li>
<li><strong>Syndromic conditions</strong> — Treacher Collins, Goldenhar, etc.</li>
</ul>
<h2 id="treatment">Treatment Options</h2>
<p>Treatment depends on the cause:</p>
<ul>
<li><strong>Dental asymmetry</strong> — orthodontics, restorative dentistry</li>
<li><strong>Skeletal asymmetry</strong> — orthodontics + orthognathic surgery, sometimes with a chin recontouring (genioplasty). See <a href="/blogs/what-is-orthognathic-surgery/">orthognathic surgery</a> and <a href="/blogs/can-jaw-surgery-improve-facial-appearance/">how it improves appearance</a></li>
<li><strong>Soft-tissue asymmetry</strong> — facial fillers, fat grafting, botulinum toxin, or facial reanimation surgery for nerve palsy</li>
<li><strong>Underlying condition</strong> — treat the syndrome or disease first</li>
</ul>
<p>3D imaging is essential for diagnosis — see <a href="/blogs/role-of-3d-virtual-planning/">3D virtual planning</a>.</p>
