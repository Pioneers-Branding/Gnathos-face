<p class="gna-lede">No face is perfectly symmetrical — that is normal. But when the difference is obvious and bothersome, or when it affects how your jaw, bite, or airway function, it is worth asking why. Facial asymmetry has many causes, ranging from genetics and dental issues to trauma, nerve conditions, growth disorders, and everyday habits. Identifying the underlying reason is the key to choosing the right treatment — and to avoiding surgery that does not address the real problem.</p>
<h2 id="categories">What Counts as Noticeable Facial Asymmetry</h2>
<p>Almost every human face has measurable left-right differences. Researchers studying frontal photographs consistently find small asymmetries in the position of the eyes, ears, nostrils, and corners of the mouth in healthy adults. These minor variations are normal and rarely need treatment.</p>
<p>Asymmetry becomes clinically noticeable when the difference between the two sides is more than a few millimetres, when one side appears visibly deviated from the midline, or when it produces symptoms such as difficulty chewing, jaw pain, tooth wear, speech changes, or breathing problems. Patients often describe it as "my jaw shifts to one side" or "my smile is crooked."</p>
<p>For the purpose of treatment planning, the underlying cause falls into one or more of these broad categories:</p>
<ul>
<li><strong>Genetic and developmental</strong> — conditions present from birth or that develop during growth</li>
<li><strong>Dental</strong> — the teeth and bite are uneven, creating an apparent facial asymmetry</li>
<li><strong>Skeletal</strong> — the jaw bones, cheekbones, or skull base are different sizes or shapes on each side</li>
<li><strong>Soft-tissue</strong> — muscles, fat, or skin differ between the two sides</li>
<li><strong>Traumatic</strong> — old injuries to bones, teeth, or the jaw joint</li>
<li><strong>Neuromuscular</strong> — facial nerve or muscle disorders</li>
<li><strong>Functional and habitual</strong> — posture, sleep position, chronic one-sided chewing</li>
</ul>
<p>In practice, more than one category is usually involved. A patient with a lower-jaw asymmetry may also chew on one side, develop a crossbite, and lose a molar on that side over time — each amplifying the original asymmetry. A specialist exam with photographs, a CBCT scan, and dental models tells you which factor is dominant and directs treatment.</p>
<h2 id="why-it-matters">Why Facial Asymmetry Matters</h2>
<p>Facial asymmetry is not only a cosmetic concern. When one side of the jaw grows longer, the bite no longer meets evenly. The teeth wear down unevenly, the jaw joint on one side carries more load, and muscles work harder to keep the mouth comfortable. Over years, this can lead to <a href="/blogs/herniated-tmj-jaw-clicking-locking-or-pain-heres-what-it-really-means/">temporomandibular joint (TMJ) pain, clicking, and locking</a>, headaches, and difficulty opening the mouth wide.</p>
<p>Severe mandibular asymmetry can also narrow the airway on one side, contributing to snoring and obstructive sleep apnoea. In these cases, <a href="/blogs/can-jaw-surgery-help-with-sleep-apnea/">jaw surgery to correct the asymmetry</a> often improves breathing at the same time.</p>
<p>Aesthetics matter too. A visibly uneven jawline or canted smile affects confidence, how you are perceived professionally, and in many patients, motivation to seek care. The good news is that identifying the dominant cause — skeletal, dental, or soft-tissue — makes treatment predictable.</p>
<h2 id="skeletal">Skeletal (Bone) Causes</h2>
<ul>
<li><strong>Hemimandibular elongation</strong> — one side of the lower jaw grew longer than the other</li>
<li><strong>Condylar hyperplasia</strong> — overgrowth of the jaw-joint condyle on one side</li>
<li><strong>Hemifacial microsomia</strong> — underdevelopment of one side of the face, from birth</li>
<li><strong>Cleft lip and palate</strong> — congenital asymmetry affecting the lip, palate, and alveolus</li>
<li><strong>Old facial fractures</strong> — improperly healed fractures from childhood trauma</li>
<li><strong>TMJ ankylosis</strong> — fusion of the jaw joint, causing asymmetric growth in children</li>
<li><strong>Skeletal Class II or III malocclusion</strong> — underbite/overbite with associated facial asymmetry</li>
</ul>
<p>These are usually addressed with combined orthodontic and orthognathic treatment. See <a href="/blogs/can-braces-fix-an-asymmetrical-jaw/">whether braces alone are enough</a>.</p>
