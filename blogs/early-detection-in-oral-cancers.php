<h2 id="burden">The Burden of Oral Cancer in India</h2>
<p>
India carries one of the heaviest burdens of oral cancer in the world. It accounts for roughly one third of all oral cancers diagnosed globally each year, and it ranks among the most common cancers in Indian men.
</p>
<p>
The disease is most often diagnosed between the ages of 40 and 65, but younger adults are increasingly affected. Most cases are linked to tobacco use, which makes the disease, in a very real sense, preventable.
</p>
<p>
The tragedy is that most patients still present at an advanced stage, when surgery is extensive and survival is poor. Early detection offers a way out of this pattern. A lesion caught at stage I can be treated with a small operation and excellent outcomes.
</p>
<h2 id="risk-factors">Risk Factors You Should Know</h2>
<p>
Tobacco in any form is the single biggest risk factor. This includes smoking cigarettes, bidis, chillums, and hookah, as well as smokeless forms such as gutka, khaini, zarda, and mishri.
</p>
<p>
Betel nut, often chewed as paan with or without tobacco, is independently carcinogenic. Regular use of betel quid causes changes in the lining of the mouth long before cancer develops.
</p>
<p>
Heavy alcohol consumption raises the risk further, especially when combined with tobacco. The two together multiply the danger rather than simply add to it.
</p>
<p>
Human papillomavirus, particularly HPV 16, is now a recognised cause of oropharyngeal cancers. Vaccination against HPV can lower this risk substantially.
</p>
<p>
Chronic sun exposure increases the risk of lip cancers, especially on the lower lip. People who work outdoors for long hours should use lip protection.
</p>
<h2 id="premalignant">Pre-Malignant Lesions</h2>
<p>
Some oral lesions are not cancer but carry a meaningful risk of becoming cancer. Identifying and monitoring these is a cornerstone of early detection.
</p>
<p>
Leukoplakia appears as a white patch that cannot be scraped off and is not explained by any other disease. The risk of malignant transformation varies with the appearance and site.
</p>
<p>
Erythroplakia is a red, velvety patch that looks more aggressive than leukoplakia. It carries a much higher malignant potential and warrants prompt biopsy.
</p>
<p>
Oral submucous fibrosis is common in India and is strongly linked to areca nut use. Patients develop stiff cheeks, reduced mouth opening, burning on eating, and altered tongue movement.
</p>
<p>
Lichen planus of the mouth can sometimes show dysplastic change. Any persistent, asymmetric, or ulcerated area within lichen planus should be reviewed by a specialist.
</p>
<h2 id="warning-signs">Early Warning Signs</h2>
<p>
A non-healing ulcer that persists beyond two weeks is the classic red flag. Most traumatic ulcers from biting or burns heal within ten to fourteen days.
</p>
<p>
Any new red or white patch inside the mouth, on the tongue, or on the gums deserves attention. Patches that change in size, colour, or surface texture are particularly concerning.
</p>
<p>
A persistent lump or thickening in the cheek, tongue, floor of the mouth, or neck should not be ignored. Difficulty opening the mouth, swallowing, or moving the tongue can also be early signs.
</p>
<p>
Persistent hoarseness, unexplained numbness of the tongue or lip, and loose teeth without an obvious dental cause can all signal an underlying malignancy. If any of these persist beyond two weeks, see a specialist.
</p>
<p>
Recognising <a href="/blogs/what-are-the-symptoms-of-oral-cancer/">oral cancer symptoms</a> early gives you the best chance of a complete cure. The disease is far easier to treat when it is small.
</p>
