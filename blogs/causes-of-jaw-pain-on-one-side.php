<p class="gna-lede">One-sided jaw pain almost always has a specific, identifiable cause. The trick is figuring out whether it's coming from the joint, the teeth, the muscles, the sinuses, or a nerve — and treating the actual source rather than just the symptom.</p>
<h2 id="common">Most Common Causes of One-Sided Jaw Pain</h2>
<p>When jaw pain is felt on only one side, the cause is usually localised. The most common culprits are:</p>
<ul>
<li><strong>Temporomandibular joint (TMJ) disorders</strong> — arthritis, disc displacement, or inflammation in one joint</li>
<li><strong>Dental problems</strong> — abscess, cracked tooth, impacted wisdom tooth, or failed root canal on one side</li>
<li><strong>Sinusitis</strong> — maxillary sinus infection usually affects only one side</li>
<li><strong>Ear infections</strong> — pain referred from the middle ear or mastoid</li>
<li><strong>Trigeminal neuralgia</strong> — sudden, electric-shock pain along the trigeminal nerve</li>
<li><strong>Muscle pain (myofascial pain)</strong> — usually from clenching or grinding on one side</li>
<li><strong>Fractures or trauma</strong> — from a recent injury to that side of the face</li>
<li><strong>Salivary gland problems</strong> — stones or infection in the parotid or submandibular gland</li>
<li><strong>Cardiac referred pain</strong> — heart attack can occasionally present as left jaw pain</li>
</ul>
<p>Because the list is long, a careful history and exam (and sometimes imaging) is essential. If you're also noticing facial puffiness or other symptoms, see <a href="/blogs/what-are-the-symptoms-of-jaw-disease/">our full jaw-disease symptom guide</a>.</p>
<h2 id="tmj">TMJ Disorders (The Most Common Cause)</h2>
<p>The TMJ is a paired joint — you have a left and a right one, and they don't always behave the same way. One-sided TMJ pain can be caused by:</p>
<ul>
<li><strong>Disc displacement</strong> — the cartilage disc slips forward, causing clicking, locking, or pain on opening</li>
<li><strong>Osteoarthritis</strong> — wear-and-tear arthritis, often worse on the side you chew on most</li>
<li><strong>Synovitis</strong> — inflammation of the joint lining</li>
<li><strong>Trauma</strong> — a past jaw injury that left one joint damaged</li>
</ul>
<p>Treatment ranges from soft diet and physiotherapy to arthrocentesis (joint wash) or arthroscopy. For severe or persistent cases, surgical options are available. Read more about <a href="/blogs/what-is-tmj-disorder/">what TMJ disorder really is</a> and the latest minimally-invasive treatments in our article on <a href="/blogs/evolution-of-tmj-arthroscopy/">TMJ arthroscopy</a>.</p>
<h2 id="dental">Dental Causes</h2>
<p>Almost any dental problem on one side can refer pain to the jaw:</p>
<ul>
<li>Tooth abscess (periapical infection)</li>
<li>Cracked or fractured tooth</li>
<li>Failed root canal — see <a href="/blogs/symptoms-of-jaw-infection-after-the-root-canal/">symptoms of jaw infection after a root canal</a></li>
<li>Partially erupted or impacted wisdom tooth — see <a href="/blogs/symptoms-of-impacted-wisdom-tooth/">impacted wisdom tooth symptoms</a></li>
<li>Severe gum disease (periodontitis) with bone loss</li>
<li>Dental decay reaching the nerve</li>
</ul>
<p>Dental pain is usually well-localised to one tooth, and the offending tooth is often sensitive to hot, cold, or biting pressure. A dental X-ray and pulp test confirm the diagnosis quickly.</p>
