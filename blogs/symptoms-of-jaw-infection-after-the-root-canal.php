<h2 id="late">Late / Serious Symptoms</h2>
<p>These suggest the infection is spreading and need same-day evaluation:</p>
<ul>
<li>Visible swelling of the face, cheek, or jaw on the affected side</li>
<li>Trismus (inability to open the mouth fully)</li>
<li>Difficulty swallowing or breathing</li>
<li>High fever (above 38.5°C)</li>
<li>Numbness of the lip, chin, or tongue (sign of nerve involvement)</li>
<li>Dental abscess with pus drainage into the mouth</li>
<li>Tooth mobility (loose tooth)</li>
</ul>
<p>If you experience any of these, go to an emergency dental or maxillofacial service immediately. For an emergency in Hyderabad, see our <a href="/blogs/emergency-treatment-for-facial-injuries-near-hyderbaad/">24/7 facial injury emergency page</a>.</p>
<h2 id="when">When to See a Specialist</h2>
<p>A general dentist handles most root canals. But you should see a maxillofacial specialist (or an endodontist) if:</p>
<ul>
<li>Pain or swelling persists or worsens after a week</li>
<li>The root canal was complex (calcified, curved, or extra canals)</li>
<li>You have a dental abscess that won't drain</li>
<li>You have facial swelling spreading toward the eye or neck</li>
<li>The root canal has failed and the tooth needs to be re-treated or removed</li>
</ul>
<p>See also <a href="/blogs/difference-between-a-dentist-and-a-maxillofacial-surgeon/">when to see a dentist vs a maxillofacial surgeon</a>.</p>
<h2 id="treatment">Treatment Options</h2>
<p>Treatment depends on the extent of infection:</p>
<ul>
<li><strong>Root canal retreatment</strong> — re-cleaning and re-sealing the canals, usually by an endodontist</li>
<li><strong>Apicoectomy</strong> — minor surgery to remove the infected root tip and seal the end</li>
<li><strong>Incision and drainage</strong> — draining the abscess to relieve pressure and pain</li>
<li><strong>Antibiotics</strong> — only as an adjunct to definitive treatment, not as a stand-alone fix</li>
<li><strong>Tooth extraction</strong> — when the tooth cannot be saved, followed by implant or bridge</li>
<li><strong>Bone grafting</strong> — to fill the defect left by infection before placing an implant</li>
</ul>
