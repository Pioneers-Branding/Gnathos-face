<p class="gna-lede">Jaw infection after a root canal is uncommon but real. The earliest signs are throbbing pain that worsens after 3–4 days, swelling of the gum or face, a pimple on the gum, persistent bad taste, fever, or a loose tooth. Prompt evaluation by an endodontist or maxillofacial surgeon usually clears the infection with retreatment, apicoectomy, or antibiotics combined with drainage.</p>
<h2 id="what">Why Jaw Infection Happens After a Root Canal</h2>
<p>A root canal removes infected pulp from inside a tooth, disinfects the canals, and seals them. Most cases heal without issue. But infection can persist or return if:</p>
<ul>
<li>A canal was missed (especially in molars with extra anatomy)</li>
<li>The seal failed and bacteria re-entered</li>
<li>A cracked root allowed reinfection</li>
<li>The tooth was not restored with a crown in time</li>
<li>An adjacent tooth or the surrounding bone was already infected</li>
</ul>
<p>When this happens, infection can spread from the tooth into the jawbone, producing the symptoms described below. See also <a href="/blogs/what-are-the-symptoms-of-jaw-disease/">the full list of jaw disease symptoms</a> for related signs.</p>
<h2 id="early">Early Warning Signs</h2>
<p>These usually appear within days to weeks of the root canal and should prompt a call to your dentist or specialist:</p>
<ul>
<li>Pain that worsens after 3–4 days instead of improving</li>
<li>Pain when biting or tapping on the treated tooth</li>
<li>Sensitivity to hot that lingers for more than 30 seconds</li>
<li>Persistent bad taste or smell from the area</li>
<li>Small pimple on the gum above the tooth (gum boil / sinus tract)</li>
<li>Swelling of the gum near the treated tooth</li>
<li>Low-grade fever</li>
</ul>
