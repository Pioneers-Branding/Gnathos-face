<h2 id="when-to-call">When to contact your surgical team</h2>
<p>Some discomfort, swelling and numbness are expected. Contact your team promptly if you notice:</p>
<ul>
  <li>You cannot keep fluids down for most of a day, or you have signs of dehydration</li>
  <li>Swelling that increases after the third or fourth day, fever, pus or a persistent bad taste</li>
  <li>Food or fluid coming out of your nose after upper jaw surgery</li>
  <li>Continuing weight loss despite following the diet plan</li>
  <li>Elastics or wires that have broken or come loose</li>
</ul>
