<h2 id="protein-and-calories">Getting enough protein and calories</h2>
<p>Your body needs more protein than usual while bone and soft tissue heal. Because liquids and purées are bulky but often low in energy, it helps to enrich them:</p>
<ul>
  <li>Make soups and porridges with milk or dal water rather than plain water</li>
  <li>Blend in paneer, curd, besan, soya or silken tofu for extra protein</li>
  <li>Add a spoon of ghee, oil, nut butter or milk powder to blended foods for extra calories</li>
  <li>Eat six to eight small meals a day instead of three large ones</li>
  <li>Use oral nutritional supplements if your team recommends them; a study of patients with wired jaws found that a planned liquid diet with supplements was associated with less weight loss and better quality of life than no dietary plan</li>
</ul>
<p>If you have diabetes, check your blood sugar more often, because sweet drinks and juices can raise it quickly and your usual meals and medicines will change. A dietitian can tailor the plan for diabetes, kidney disease or a vegetarian or vegan diet.</p>

<h2 id="hydration">Staying hydrated</h2>
<p>It is easy to become dehydrated when drinking is slow, especially during a Hyderabad summer. Sip fluids steadily through the day rather than waiting until you feel thirsty. Warning signs of dehydration include dark yellow, strong-smelling urine, passing urine less often, feeling dizzy or light-headed, tiredness and a dry mouth and lips. ORS and tender coconut water are useful if you are not drinking enough.</p>
<p>Constipation is also common, because of pain medicines, less fibre and less fluid. Plenty of fluids, blended fruit and, if your doctor agrees, a fibre supplement such as isabgol taken with enough water can help.</p>

<h2 id="oral-hygiene">Keeping your mouth clean while you heal</h2>
<p>Food left around the stitches inside your mouth can cause infection, so cleaning is as important as eating:</p>
<ul>
  <li>Rinse after every meal and snack with the mouthwash you have been prescribed, or with lukewarm salt water if advised</li>
  <li>Use a soft, small toothbrush to clean your teeth gently from when your surgeon says it is safe, avoiding the incisions</li>
  <li>Use a syringe of water to flush food from around braces, elastics or wires</li>
  <li>Keep your lips moisturised, as they often become dry and cracked</li>
</ul>
