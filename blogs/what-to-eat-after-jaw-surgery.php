  <p><strong>Get emergency help</strong> by calling 108 or going to the nearest emergency department if you have difficulty breathing, are choking, or have bleeding that does not stop with firm pressure. If your jaws are wired, make sure you know what your team has told you to do if you feel sick or vomit.</p>
