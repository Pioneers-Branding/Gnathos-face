<p class="gna-lede">After jaw surgery you will usually move through three stages: liquids for the first days to two weeks, then smooth blended foods, then soft foods you can mash with a fork, before gradually returning to normal eating from around six weeks. The aim at every stage is the same: enough calories, protein and fluid to heal, without putting strain on the healing bones. Your own surgeon's instructions always come first, because timings vary with the operation.</p>

<h2 id="why-diet-matters">Why your diet matters after jaw surgery</h2>
<p>After corrective jaw surgery or a jaw fracture repair, the bones need several weeks to knit together. During that time, chewing is limited by swelling, stiffness, numbness and sometimes by elastics or wires that hold the bite in place. Eating becomes slow and tiring, and many people simply eat less than they need.</p>
<p>Studies consistently show that people lose weight after jaw surgery. A recent prospective study found an average loss of around three to four kilograms in the first few weeks, with greater losses after double jaw surgery, and weight usually recovers gradually over the following months. Losing some weight is common, but losing too much can slow healing, reduce energy and lower your mood.</p>
<div class="gna-keypoints">
  <h3>Key points</h3>
  <ul>
    <li>Plan for three stages: liquids, blended foods, then soft foods. Your surgeon will tell you when to move on.</li>
    <li>Eat little and often, six to eight times a day, and make every sip count with protein and calories.</li>
    <li>Keep drinks and food lukewarm: numb lips may not feel heat.</li>
    <li>Rinse your mouth after every meal or snack to protect the wounds inside your mouth.</li>
    <li>Avoid hard, crunchy and chewy foods until your surgeon clears you, usually after about six weeks.</li>
  </ul>
</div>

<h2 id="before-surgery">Preparing before surgery</h2>
<p>A little preparation makes the first weeks much easier:</p>
<ul>
  <li><strong>Equipment:</strong> a good blender or mixer-grinder, a fine strainer, measuring cups, and a few large syringes or a sipper cup. Feeding syringes are often provided by the hospital.</li>
  <li><strong>Stock up:</strong> milk, curd, paneer, ragi flour, dals, rice, oats, bananas, soft fruits, ghee, nut butters, ORS sachets and any nutritional supplement your team recommends.</li>
  <li><strong>Plan help:</strong> ask a family member to prepare meals for the first week or two, when you will tire easily.</li>
  <li><strong>Know your starting weight</strong> so you can track it each week.</li>
</ul>
<p>If you have diabetes, kidney disease or follow a special diet, tell your team before surgery so the plan can be adapted. Our <a href="/blogs/jaw-surgery-orthognathic-complete-guide-for-patients/">complete guide to orthognathic surgery</a> explains the rest of the preparation process.</p>

<h2 id="stage-1-liquids">Stage 1: liquids (first days to about two weeks)</h2>
<p>In the first days, everything should be smooth and thin enough to sip from a cup or take with a syringe, with no lumps or bits. Nausea from the anaesthetic is common at first, so start with small sips.</p>
<ul>
  <li>Water, oral rehydration solution (ORS) and tender coconut water</li>
  <li>Thin buttermilk (chaas) and thin lassi</li>
  <li>Strained dal water and mild, lukewarm rasam or clear vegetable or chicken soup</li>
  <li>Milk, and milkshakes made with banana or chikoo, strained if needed</li>
  <li>Thin, strained ragi malt (ragi java or ambali)</li>
  <li>Diluted non-citrus fruit juices; citrus juices may sting the wounds</li>
  <li>Protein drinks or oral nutritional supplements, if advised by your team</li>
</ul>
<p>Use a syringe, a cup or a spoon as you have been shown, place food towards the back teeth on the side away from any tender areas, and take your time. If your jaws are wired or held with tight elastics, every meal must pass through the small gaps between your teeth, and this stage lasts until they are released. Our guide to <a href="/blogs/broken-jaw-treatment-wiring-vs-plates/">wiring versus plates for a broken jaw</a> explains when wiring is used.</p>

<h2 id="stage-2-blended">Stage 2: blended and puréed foods (around weeks two to four)</h2>
<p>Once you are comfortable with liquids and your surgeon agrees, you can move to thicker, completely smooth foods with the texture of a thick soup or porridge. Blend thoroughly, and thin with milk, water or dal water until there are no lumps.</p>
<ul>
  <li><strong>Blended khichdi</strong> made with extra dal and a spoon of ghee</li>
  <li>Dal and rice blended together, or a smooth sambar with soaked idli blended in</li>
  <li>Vegetable soups such as pumpkin, carrot, bottle gourd or spinach, blended with dal or paneer for protein</li>
  <li>Thick ragi porridge, oats porridge or smooth suji kheer</li>
  <li>Plain curd, or curd blended with banana or mango</li>
  <li>Smooth mashed potato thinned with milk</li>
  <li>For non-vegetarians: soft-cooked chicken or fish blended into a soup</li>
</ul>

<h2 id="stage-3-soft">Stage 3: soft foods and returning to normal (around weeks four to six onwards)</h2>
<p>Soft foods are those you can break with a fork or the side of a spoon, needing very little chewing. Good options include soft idli, curd rice, pongal, soft khichdi, upma, well-cooked dal and rice, scrambled eggs, soft paneer bhurji, steamed fish without bones, well-cooked vegetables, ripe papaya and banana.</p>
<p>From around six weeks, if your surgeon is happy with healing, you can gradually reintroduce foods that need more chewing, such as soft chapati, dosa and well-cooked meat. Your jaw muscles will feel weak and stiff at first; start with small pieces and build up over several weeks. Full chewing strength can take a few months to return.</p>
<p>Until you are cleared, avoid:</p>
<ul>
  <li>Hard and crunchy foods: murukku, chakli, pakoda, papad, chikki, whole nuts, toast and popcorn</li>
  <li>Chewy foods: tough meat, crusty bread, chewing gum and toffees</li>
  <li>Foods with bones, or foods you bite with the front teeth, such as corn on the cob or sugarcane</li>
  <li>Very spicy or very hot food, which can irritate the wounds</li>
  <li>Alcohol, smoking and all tobacco, including gutka and khaini, which slow healing and raise the risk of infection</li>
</ul>

