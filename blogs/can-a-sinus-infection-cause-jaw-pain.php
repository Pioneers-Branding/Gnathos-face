<p class="gna-lede">Yes — a sinus infection (sinusitis) is a surprisingly common cause of upper-jaw and toothache-like pain. The maxillary sinuses sit just above your upper molars and premolars, and when they fill with fluid and inflammation, the pressure is felt directly in the jaw.</p>
<h2 id="anatomy">The Anatomy: Why Sinuses &amp; Jaw Are Linked</h2>
<p>The maxillary sinuses are air-filled cavities located inside the cheekbones, directly above the roots of the upper molars and premolars. In many people, the bone separating the sinus floor from the tooth roots is paper-thin — sometimes just a millimetre or two. They share the same nerve supply (the infraorbital and posterior superior alveolar nerves), so pain originating in the sinus cavity is often felt as tooth or jaw pain.</p>
<p>Because of this intimate anatomical relationship, dental infections can spread upward into the sinus (causing odontogenic sinusitis), and sinus infections can radiate downward into the teeth and jaw. For a deeper look at the wider topic of <a href="/blogs/causes-of-jaw-pain-on-one-side/">jaw pain on one side</a> — including other causes — read our dedicated guide.</p>
<h2 id="how">How Sinusitis Causes Jaw Pain</h2>
<p>When the lining of the maxillary sinus becomes inflamed and swollen, the sinus cannot drain properly. Fluid accumulates, pressure builds, and the inflammation irritates the nerves that run along the floor of the sinus. The brain, which doesn't always know exactly where the signal is coming from, often interprets this as tooth or jaw pain — a phenomenon called <strong>referred pain</strong>.</p>
<p>Several mechanisms drive this:</p>
<ul>
<li><strong>Direct pressure</strong> on the tooth roots through the thin sinus floor</li>
<li><strong>Inflammatory mediators</strong> (cytokines, prostaglandins) that sensitise nearby nerves</li>
<li><strong>Shared nerve pathways</strong> that confuse the brain's pain map</li>
<li><strong>Postnasal drip</strong> that irritates the throat and jaw muscles</li>
</ul>
<p>Sinus-related jaw pain is most often felt in the upper back teeth and the upper jaw, but it can radiate to the lower jaw as well. If you're also dealing with facial swelling or pressure, see <a href="/blogs/what-are-the-symptoms-of-jaw-disease/">the full list of jaw disease symptoms</a> to rule out other causes.</p>
