<h2 id="symptoms">Symptoms to Watch For</h2>
<p>Sinusitis-related jaw pain usually comes with other sinus symptoms. Look for:</p>
<ul>
<li>Pressure or fullness under the eyes and in the cheeks</li>
<li>Nasal congestion or coloured nasal discharge</li>
<li>Reduced sense of smell</li>
<li>Headache, especially when bending forward</li>
<li>Pain in multiple upper back teeth (rather than one specific tooth)</li>
<li>Pain that worsens with sudden head movements or lying down</li>
<li>Fatigue, low-grade fever, and general malaise</li>
<li>Ear fullness or <a href="/blogs/does-ear-infection-cause-jaw-pain/">ear-related discomfort</a></li>
</ul>
<p>Symptoms lasting less than 4 weeks are <strong>acute sinusitis</strong>. Beyond 12 weeks, it becomes <strong>chronic sinusitis</strong> and may need specialist evaluation.</p>
<h2 id="dental">Sinus Pain vs. Dental Pain</h2>
<p>Telling sinus pain apart from a dental problem can be tricky. The table below summarises the key differences:</p>
<ul>
<li><strong>Number of teeth affected:</strong> sinus pain usually affects several upper back teeth; dental pain is typically localised to one tooth</li>
<li><strong>Response to hot/cold:</strong> sinus pain is unaffected; a sensitive tooth will respond</li>
<li><strong>Response to biting:</strong> sinus pain does not worsen with biting; a cracked tooth or abscess will</li>
<li><strong>Associated symptoms:</strong> sinus pain comes with nasal congestion and facial pressure; dental pain may have gum swelling or a visible cavity</li>
<li><strong>Pain triggers:</strong> sinus pain worsens with head movement; dental pain often worsens at night</li>
</ul>
<p>When in doubt, see both a dentist and a maxillofacial specialist. At <a href="/">Gnathos Facial</a>, we work closely with endodontists and ENT surgeons to pinpoint the source of facial pain quickly.</p>
<h2 id="treatment">Treatment &amp; When to See a Specialist</h2>
<p>Most acute sinus infections resolve with conservative treatment:</p>
<ul>
<li>Saline nasal irrigation (neti pot or rinse bottle)</li>
<li>Nasal corticosteroid sprays (fluticasone, mometasone)</li>
<li>Decongestants (short-term use only)</li>
<li>Pain relief with paracetamol or ibuprofen</li>
<li>Antibiotics (only for confirmed bacterial sinusitis)</li>
</ul>
<p>See a specialist promptly if you have:</p>
<ul>
<li>Pain that lasts more than 10 days without improvement</li>
<li>High fever, severe headache, or vision changes</li>
<li>Swelling of the cheek or around the eye</li>
<li>Recurrent sinus infections (more than 3–4 per year)</li>
<li>Suspected dental origin (odontogenic sinusitis) — this often needs both ENT and dental treatment</li>
</ul>
<p>For persistent or recurrent cases, a CBCT scan of the sinuses and jaw gives a clear picture. If a tooth is the source, <a href="/blogs/symptoms-of-jaw-infection-after-the-root-canal/">root canal infections and jaw symptoms</a> may need to be addressed together.</p>
